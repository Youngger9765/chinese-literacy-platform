describe('#3217 刻意放棄的：福相', () => {
  /**
   * `福*` 在 v[0]，而第一 pass（前置樣式）永遠先於第二 pass（後置樣式），
   * 所以它結構上一定贏 v[1] 的 `*倚` —— 「禍福相倚」會被讀成 ㄒㄧㄤˋ。
   *
   * 全庫 175 課裡「福相」出現 3 次，**每一次都是「禍福相倚」**，
   * 「福相」（有福氣的面相）本身 0 次 —— 所以拿掉 `福*` 零風險。
   * 同 #3173 拿掉 `多*`（多難興邦全庫 0 次）的判準。
   *
   * ⚠️ 代價寫在這裡而不是註解掉：哪天課文真的出現「一臉福相」，它會讀成 ㄒㄧㄤ，
   * 屆時要加的是 `福*相` 這種更長的前置樣式，不是把 `福*` 加回來。
   */
  it('「禍福相倚」是 ㄒㄧㄤ —— 這是拿掉 福* 換來的', () => {
    expect(xiang('這件事表現了禍福相倚的智慧')).toBe('xiang1');
  });
});

describe('#3217 正向對照：量具本身沒壞', () => {
  it('字型表有兩個讀音，且處理器真的會因詞而異', () => {
    expect(Object.keys(XIANG_READINGS)).toHaveLength(2);
    // 這條若紅，代表處理器整個沒動作，上面所有斷言都不算數
    expect(xiang('拿起相機拍下來')).not.toBe(xiang('大家會互相幫忙'));
  });
});
